"""Complete the CosQA valid-split HyDE run using verified shared E5 vectors.

HyDE hypotheses are generated by the notebook with the pinned Transformers
runtime. Corpus embeddings can be reused across qrels splits because they
depend on the immutable corpus and E5 controls, not on qrels. This script
checks those controls and requires exact equality with the independent valid
E5 candidate rankings before accepting the reused vectors.
"""

